import {expect,test} from '@playwright/test';

test('city-building and mayor decisions stay in one playable map screen',async ({page})=>{
  const errors:string[]=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto('/');
  const canvas=page.locator('.map-host canvas');
  await expect(canvas).toBeVisible({timeout:30_000});
  const nav=page.getByRole('navigation',{name:'メインメニュー'});
  await expect(nav.getByRole('button')).toHaveCount(2);
  await expect(nav.getByRole('button',{name:'街を運営'})).toHaveAttribute('aria-current','page');
  const open=page.getByRole('button',{name:'市長コマンドを開く'});
  await expect(open).toBeVisible();
  await open.click();
  const operations=page.getByRole('region',{name:'市長コマンドの操作'});
  await expect(operations).toBeVisible();
  await operations.getByRole('button',{name:'環境優先'}).click();
  await expect(operations.getByRole('button',{name:'環境優先'})).toHaveAttribute('aria-pressed','true');
  await expect(nav.getByRole('button',{name:'街を運営'})).toHaveAttribute('aria-current','page');
  await operations.getByRole('button',{name:'税金・予算'}).click();
  const tax=operations.locator('#mayor-tax');
  const oldRate=Number(await tax.inputValue());
  await tax.focus();
  await tax.press('ArrowRight');
  await expect(tax).toHaveValue(String(oldRate+1));
  const plans=operations.getByRole('group',{name:'地図から維持方針を変更'});
  await plans.getByRole('button').last().click();
  await expect(plans.getByRole('button').last()).toHaveAttribute('aria-pressed','true');
  await operations.getByRole('button',{name:'大型投資'}).click();
  await expect(operations.getByRole('button',{name:'地図から交通ネットワーク強化へ投資'})).toBeVisible();
  await operations.getByRole('button',{name:'街の診断'}).click();
  await expect(operations.getByRole('button',{name:'交通量'})).toBeVisible();
  await operations.getByRole('button',{name:'交通量'}).click();
  await expect(operations).toBeHidden();
  await expect(page.locator('.traffic-legend')).toBeVisible();
  await expect(canvas).toBeVisible();
  await expect(nav.getByRole('button',{name:'街を運営'})).toHaveAttribute('aria-current','page');
  expect(errors).toEqual([]);
});

test('detailed statistics stay under one data destination with fast return to the same city map',async ({page})=>{
  await page.goto('/');
  const canvas=page.locator('.map-host canvas');
  await expect(canvas).toBeVisible({timeout:30_000});
  const nav=page.getByRole('navigation',{name:'メインメニュー'});
  await canvas.evaluate(el=>{(el as HTMLCanvasElement).dataset.tabStable='true';});
  await nav.getByRole('button',{name:'都市データ'}).click();
  const tabs=page.getByRole('tablist',{name:'都市データの表示切替'});
  await expect(tabs.getByRole('tab')).toHaveCount(4);
  await tabs.getByRole('tab',{name:'住民と人口'}).click();
  await expect(page.getByText('住民と都市の成長')).toBeVisible();
  await tabs.getByRole('tab',{name:'交通・物流'}).click();
  await expect(page.getByRole('meter',{name:'推定混雑度'})).toBeVisible();
  await tabs.getByRole('tab',{name:'財政と経済'}).click();
  await expect(page.locator('.finance-panel')).toBeVisible();
  await tabs.getByRole('tab',{name:'政策と行政'}).click();
  await expect(page.getByText('市政方針')).toBeVisible();
  await tabs.getByRole('button',{name:'地図に戻る'}).click();
  await expect(nav.getByRole('button',{name:'街を運営'})).toHaveAttribute('aria-current','page');
  await expect(canvas).toBeVisible();
  await expect(canvas).toHaveAttribute('data-tab-stable','true');
});